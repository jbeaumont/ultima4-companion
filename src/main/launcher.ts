// Launches Ultima IV in DOSBox with a companion-generated config, without
// touching the game folder. Two profiles:
//  - play: windowed beside the companion, real saves (GOG's cloud_saves overlay)
//  - test: turbo CPU, fixed window position/size for automated play-testing, and
//          the test-mode save overlay (only available in a --test instance)
import { spawn } from 'node:child_process'
import { existsSync } from 'node:fs'
import { mkdir, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { findPids } from './memory/win32'

export type LaunchProfile = 'play' | 'test'

export interface LaunchOptions {
  profile: LaunchProfile
  gameDir: string
  overlayDir: string
  /** Where the generated config is written (the companion's userData). */
  confDir: string
}

export const TEST_WINDOW = { x: 0, y: 0, width: 960, height: 600 }

/** DOSBox config layered after GOG's base config; later files override earlier ones. */
export function buildConf(o: Omit<LaunchOptions, 'confDir'>): string {
  const test = o.profile === 'test'
  return [
    '# Generated by Ultima IV Companion; safe to delete.',
    '[sdl]',
    'fullscreen=false',
    // never capture the mouse on click (the play-test driver clicks to focus)
    'autolock=false',
    'output=opengl',
    `windowresolution=${test ? `${TEST_WINDOW.width}x${TEST_WINDOW.height}` : '1280x800'}`,
    '[render]',
    'aspect=false',
    'frameskip=0',
    '[cpu]',
    // test: as fast as the host allows; play: keep GOG's authentic speed (base config)
    ...(test ? ['core=dynamic', 'cycles=max'] : []),
    '[autoexec]',
    '@ECHO OFF',
    `mount C "${o.gameDir}"`,
    `mount C "${o.overlayDir}" -t overlay`,
    'c:',
    'cls',
    'ultima.com',
    'exit',
    ''
  ].join('\r\n')
}

export class LaunchRefused extends Error {}

export async function launchGame(o: LaunchOptions): Promise<{ pid: number | undefined }> {
  const dosboxDir = join(o.gameDir, 'DOSBOX')
  const exe = join(dosboxDir, 'dosbox.exe')
  const baseConf = join(o.gameDir, 'dosboxULTIMA4.conf')
  if (!existsSync(exe) || !existsSync(baseConf)) throw new LaunchRefused('DOSBox from the GOG install was not found.')
  if ((await findPids('dosbox.exe')).length) throw new LaunchRefused('DOSBox is already running.')

  await mkdir(o.overlayDir, { recursive: true })
  await mkdir(o.confDir, { recursive: true })
  const conf = join(o.confDir, `dosbox-${o.profile}.conf`)
  await writeFile(conf, buildConf(o))

  const child = spawn(exe, ['-conf', baseConf, '-conf', conf, '-noconsole'], {
    cwd: dosboxDir,
    detached: true,
    stdio: 'ignore',
    windowsHide: false,
    // SDL 1.2 (DOSBox 0.74) honours this for the initial window position
    // windib makes SDL read keys from window messages, so the play-test driver can post them
    env: { ...process.env, ...(o.profile === 'test' ? { SDL_VIDEO_WINDOW_POS: `${TEST_WINDOW.x},${TEST_WINDOW.y}`, SDL_VIDEODRIVER: 'windib' } : { SDL_VIDEO_CENTERED: '1' }) }
  })
  child.unref()
  return { pid: child.pid }
}
